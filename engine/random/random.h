#pragma once

#include <cstdint>

/**
 * Повторяемые случайные числа для аудиопотока (D-105): без памяти и блокировок,
 * одно и то же зерно даёт одну и ту же последовательность на любой машине
 */
class Random {
  public:
    /**
     * Зерно модуля в голосе. Зависит только от ID модуля и номера голоса, а не от порядка
     * создания, поэтому рендер того же файла повторяется до бита
     */
    static uint64_t makeSeed(uint32_t moduleId, uint32_t voice);

    void setSeed(uint64_t seed);

    /**
     * Вернуться к началу последовательности
     */
    void rewind();

    /**
     * Следующее число в [0, 1)
     */
    float nextUnit();

  private:
    uint64_t seed = 0;
    uint64_t state = 0;
};
