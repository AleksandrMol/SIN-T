#pragma once

#include <map>
#include <optional>

#include "../../engine/synthModel/synthModel.h"

// Тип модуля со своей лицевой стороной блока (D-108). Строка постоянная: по ней тип ищется в пресетах (D-020)
inline constexpr const char* OSCILLATOR_TYPE = "oscillator";

/**
 * Узкий блок: у модуля мало ручек, и он не генератор. Таких ручек в ряду две, а не четыре
 */
bool isSmallBlock(const ModuleInstance& module);

/**
 * Высота блока модуля в dp, как его рисует редактор: по ней авторасстановка ставит блоки колонки друг под другом (D-108).
 * С настоящей высотой её сверяет тест редактора, поэтому правка стилей блока без правки здесь не пройдёт
 */
float getBlockHeight(const ModuleInstance& module);

/**
 * Авторасстановка блоков одного графа (D-068): старые пресеты положений не содержат (D-065).
 * Звук идёт слева направо, колонка — длина самого длинного пути от источника, выход стоит последним.
 * Блоки колонки стоят друг под другом по своей высоте, модуляторы без аудиопортов идут отдельным рядом
 * под самой длинной колонкой. Результат зависит только от модели.
 * graph — генератор, подграф которого расставляется. Пусто — главный граф
 */
std::map<ModuleId, ModulePosition> computeLayout(const SynthModel& model, std::optional<ModuleId> graph);
