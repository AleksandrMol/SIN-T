/**
 * Текстуры металла считаются кодом, а не читаются из файлов: плагину не нужны ни файлы рядом, ни декодер PNG.
 * В стилях их подключают как картинку: image(sint:brushed repeat). Имена:
 * - sint:brushed — тонкая шлифовка без приметных деталей, повтор на одинаковых блоках незаметен;
 * - sint:worn — шлифовка, пятна и микроцарапины для больших панелей;
 * - sint:scuffed — пятна и царапины без шлифовки для углублённых тёмных панелей.
 * Каждая текстура — бесшовная плитка и полупрозрачный слой: светлые места белые, тёмные чёрные,
 * поэтому она ложится на любой тон и в среднем его не меняет.
 * Считается один раз на процесс и одинаково на любой платформе. Пустой указатель — имя не наше
 */
const TextureImage* findMetalTexture(std::string_view source);
