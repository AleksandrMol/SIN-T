#pragma once

#include <cstddef>

/**
 * Сколько раз программа выделила память через new. Нужен для проверки того,
 * что аудиопоток не выделяет память (D-023)
 */
size_t getAllocationCount();

/**
 * Сколько раз текущий поток выделил или освободил память. Другие потоки на счёт не влияют,
 * поэтому им можно мерить аудиопоток, пока главный поток собирает планы
 */
size_t getThreadMemoryOperations();
